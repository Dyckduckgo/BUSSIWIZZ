"""
Structured Pydantic Models for Multi-Agent Stock Research Pipeline
Defines:
- Evidence: Strongly typed evidence items collected by research agents
- VerifiedEvidence: Verifier audit result for every claim
- VerificationReport: Comprehensive audit summary of claims
- ResearchScore: Explainable 0-100 institutional score across 7 dimensions
- ScenarioCases: Bull, Base, and Bear scenarios
- AnalystReport: Final comprehensive analytical report
"""

from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field, field_validator


class Evidence(BaseModel):
    """
    Standardized, structured evidence object extracted by research agents.
    Prevents passing large unstructured prose between agents.
    """
    claim: str = Field(description="The factual or analytical claim asserted by the agent")
    source_url: str = Field(default="", description="Direct URL, DOI, or official filing source link")
    source_name: str = Field(default="", description="Publisher, EDGAR form, portal, or database name")
    source_date: str = Field(default="", description="Publication date or filing period")
    source_type: str = Field(
        default="NEWS",
        description="Source classification: SEC_FILING, FINANCIAL_API, ACADEMIC_PAPER, NEWS, OFFICIAL_PR"
    )
    evidence_text: str = Field(default="", description="Verbatim citation or extracted snippet supporting the claim")
    confidence: float = Field(ge=0.0, le=1.0, default=0.8, description="Initial confidence score from the research agent")
    agent_name: str = Field(description="Name of the agent that produced this evidence: WebAgent, FinancialAgent, SECAgent, RDAgent")
    epistemic_status: str = Field(default="FACT", description="Epistemic status: FACT, INFERENCE, SPECULATION")
    numerical_value: Optional[float] = Field(default=None, description="Extracted numerical metric value if applicable")
    metric_name: Optional[str] = Field(default=None, description="Name of the quantitative metric if applicable")

    def to_dict(self) -> Dict[str, Any]:
        """Returns clean dictionary representation."""
        return self.model_dump()


class VerificationCheck(BaseModel):
    """Detailed audit results across the 7 mandatory verifier criteria."""
    source_supports_claim: bool = Field(description="1. Does the source support the claim?")
    source_trustworthy: bool = Field(description="2. Is the source trustworthy?")
    is_current: bool = Field(description="3. Is it current?")
    numerical_value_correct: bool = Field(description="4. Is the numerical value correct?")
    conclusion_proportional_to_evidence: bool = Field(description="5. Is the conclusion stronger than the evidence?")
    no_unresolved_conflicts: bool = Field(description="6. Are there conflicting sources?")
    epistemic_status: str = Field(description="7. Is this fact, inference or speculation?")
    notes: str = Field(default="", description="Detailed audit remarks")


class VerifiedEvidence(BaseModel):
    """A claim evaluated and audited by the Verifier agent."""
    evidence: Evidence = Field(description="The original evidence item")
    verified: bool = Field(description="True if verified for factual use, False if rejected")
    verification_reason: str = Field(description="Explicit explanation of why claim was verified or rejected")
    checks: Optional[VerificationCheck] = Field(default=None, description="Individual checklist audit results")


class VerificationReport(BaseModel):
    """Aggregate audit report generated by the Verifier agent."""
    total_claims: int
    verified_count: int
    rejected_count: int
    verified_items: List[VerifiedEvidence] = Field(default_factory=list)
    rejected_items: List[VerifiedEvidence] = Field(default_factory=list)

    def summary(self) -> str:
        return (
            f"Verification Complete: {self.verified_count}/{self.total_claims} claims verified. "
            f"({self.rejected_count} rejected due to speculation, untrusted sources, or unsupported claims)"
        )


class ResearchScore(BaseModel):
    """
    Explainable institutional research score across 7 distinct dimensions.
    Max total score is 100.
    """
    total_score: float = Field(ge=0.0, le=100.0, description="Composite research score out of 100")
    business_quality: float = Field(ge=0.0, le=20.0, description="Business Quality: 0-20")
    financial_health: float = Field(ge=0.0, le=20.0, description="Financial Health: 0-20")
    growth: float = Field(ge=0.0, le=15.0, description="Growth Momentum: 0-15")
    competitive_advantage: float = Field(ge=0.0, le=15.0, description="Competitive Moat: 0-15")
    valuation: float = Field(ge=0.0, le=15.0, description="Valuation Multiple Attractiveness: 0-15")
    rd_innovation: float = Field(ge=0.0, le=10.0, description="R&D / Technology Innovation: 0-10")
    risk_profile: float = Field(ge=0.0, le=5.0, description="Risk & Resilience Profile: 0-5")
    explanation: str = Field(description="Clear breakdown of how each dimension score was derived")
    disclaimer: str = Field(
        default=(
            "Disclaimer: This research score is a heuristic quantitative model output based on publicly "
            "available financial and corporate disclosures. It does not constitute a price prediction, "
            "investment recommendation, endorsement, or personalized financial advice."
        ),
        description="Mandatory compliance disclaimer"
    )

    def to_dimensions_dict(self) -> Dict[str, float]:
        return {
            "Business Quality (0-20)": round(self.business_quality, 1),
            "Financial Health (0-20)": round(self.financial_health, 1),
            "Growth (0-15)": round(self.growth, 1),
            "Competitive Advantage (0-15)": round(self.competitive_advantage, 1),
            "Valuation (0-15)": round(self.valuation, 1),
            "R&D / Innovation (0-10)": round(self.rd_innovation, 1),
            "Risk Profile (0-5)": round(self.risk_profile, 1),
            "Total Score (0-100)": round(self.total_score, 1),
        }


class ScenarioCases(BaseModel):
    """Scenario modeling: Bull, Base, and Bear cases."""
    bull_case: str = Field(description="Optimistic upside scenario with clear catalysts and operational milestones")
    base_case: str = Field(description="Most likely baseline scenario grounded in current growth and profitability trends")
    bear_case: str = Field(description="Downside risk scenario considering competitive threats and execution hurdles")


class AnalystReport(BaseModel):
    """Complete institutional equity research report produced by the Final Analyst."""
    company: str
    ticker: str
    company_overview: str
    financial_health: str
    profitability: str
    growth: str
    valuation: str
    competitive_advantage: str
    management: str
    rd_and_innovation: str
    recent_developments: str
    risks: str
    catalysts: str
    scenarios: ScenarioCases
    score: ResearchScore
    verified_evidence_count: int
    rejected_evidence_count: int
    full_markdown: str
    disclaimer: str = Field(
        default="This report is produced for informational purposes only and does not constitute personalized financial advice."
    )
